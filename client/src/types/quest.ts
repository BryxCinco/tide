export type QuestCategory = 'focus' | 'journal' | 'tasks' | 'wellness' | 'growth';
export type QuestRecurrenceType = 'daily' | 'weekly' | 'custom';

/** Shared by DailyQuestCard, QuestFormModal, and QuestManagerModal so a category's color
 * is defined in exactly one place. */
export const QUEST_CATEGORY_COLOR: Record<QuestCategory, string> = {
  focus: '#14B8A6',
  journal: '#8B5CF6',
  tasks: '#0EA5E9',
  wellness: '#F97316',
  growth: '#EC4899',
};

export const QUEST_CATEGORY_LABEL: Record<QuestCategory, string> = {
  focus: 'Focus',
  journal: 'Journal',
  tasks: 'Tasks',
  wellness: 'Wellness',
  growth: 'Growth',
};

export interface Quest {
  id: string;
  title: string;
  description: string;
  /** Lucide icon name, as a plain string (same convention as Activity.icon). */
  icon: string;
  category: QuestCategory;
  xp: number;
  isCompleted: boolean;
  completedAt?: string;
  /** Local "YYYY-MM-DD" the quest belongs to — see utils/formatDate.ts's toDateKey. */
  date: string;
  /** User-created (via QuestFormModal) vs generated by questGenerator.ts. Only custom
   * quests can be deleted outright — see quests.js's DELETE route. */
  isCustom: boolean;
  /** Hidden from the Daily Quest card while false, but still editable from
   * QuestManagerModal — the "pause" alternative to deleting a system quest. */
  isActive: boolean;
  isRecurring: boolean;
  /** Only meaningful when isRecurring is true. Stored/editable now; actually regenerating
   * a recurring quest into future days isn't implemented yet — see questStore.ts. */
  recurrenceType: QuestRecurrenceType | null;
}
