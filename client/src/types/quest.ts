export interface Quest {
  id: string;
  title: string;
  description: string;
  /** Lucide icon name, as a plain string (same convention as Activity.icon). */
  icon: string;
  category: QuestCategory;
  /** 1=Common..5=Legendary — see QUEST_TIER_META. Determines auto-computed xp. */
  tier: QuestTier;
  /** Auto-computed from tier (+ difficulty at creation, + streak/diversity bonuses once
   * completed — see server/lib/questXp.js). Never hand-typed by the user anymore. */
  xp: number;
  isCompleted: boolean;
  completedAt?: string;
  /** Local "YYYY-MM-DD" the quest belongs to — see utils/formatDate.ts's toDateKey. */
  date: string;
  /** User-created (via QuestFormModal) vs generated by questGenerator.ts. Only custom
   * quests can be deleted outright — see quests.js's DELETE route. */
  isCustom: boolean;
  /** Hidden from the Quest card while false, but still editable from QuestManagerModal —
   * the "pause" alternative to deleting a system quest. */
  isActive: boolean;
  isRecurring: boolean;
  /** Only meaningful when isRecurring is true. Stored/editable now; actually regenerating
   * a recurring quest into future days isn't implemented yet — see questStore.ts. */
  recurrenceType: QuestRecurrenceType | null;
  /** True for anything from generateDailyQuests/suggestTideQuest, false for a user's own
   * manual "+ Add Quest". */
  isAgentic: boolean;
  /** Why the AI picked this quest (e.g. "You haven't journaled in 10 days") — shown as the
   * quest's description line when present, since it's more specific than a generic template
   * description. Null for manually-created quests. */
  generationReason: string | null;
}
